export type CountryEntry = {
  code: string;
  ar: string;
  en: string;
};

export function countryCodeToFlag(code: string): string {
  if (!code || code.length !== 2) return "";
  const base = 0x1f1e6;
  return String.fromCodePoint(
    code.toUpperCase().charCodeAt(0) - 65 + base,
    code.toUpperCase().charCodeAt(1) - 65 + base,
  );
}

export function sortCountries(countries: CountryEntry[], lang: "ar" | "en"): CountryEntry[] {
  return [...countries].sort((a, b) =>
    lang === "ar"
      ? a.ar.localeCompare(b.ar, "ar", { sensitivity: "base" })
      : a.en.localeCompare(b.en, "en", { sensitivity: "base" }),
  );
}

export function filterCountries(countries: CountryEntry[], query: string): CountryEntry[] {
  const q = query.toLowerCase().trim();
  if (!q) return countries;
  return countries.filter(
    (c) =>
      c.ar.toLowerCase().includes(q) ||
      c.en.toLowerCase().includes(q) ||
      c.code.toLowerCase().includes(q),
  );
}

