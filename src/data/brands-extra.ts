/** Stable slug + deterministic brand color so tiles stay consistent between renders. */
export function seedSlug(name: string) {
  return name
    .toLowerCase()
    .replace(/&/g, "-and-")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

export function seedColor(name: string) {
  let h = 0;
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) % 360;
  return `oklch(0.52 0.14 ${h})`;
}
